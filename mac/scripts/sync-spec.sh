#!/bin/bash
# Copies rules from spec/ into the build as Swift source: spec/ stays the only source of truth,
# the app needs no resource bundle. `swift run redakciya-checks` fails if the copy is stale.
set -euo pipefail
cd "$(dirname "$0")/.."
OUT=Sources/RedakciyaKit/Editing/BundledLinkRules.swift
{
    echo "// Generated by scripts/sync-spec.sh from spec/link-rules.json. Do not edit."
    echo "enum BundledLinkRules {"
    echo "    static let json = #\"\"\""
    cat ../spec/link-rules.json
    echo "\"\"\"#"
    echo "}"
} > "$OUT"
echo "Wrote $OUT"

OUT=Sources/RedakciyaKit/Archive/BundledRecoveryWords.swift
{
    echo "// Generated by scripts/sync-spec.sh from spec/recovery-words-ru.txt. Do not edit."
    echo "enum BundledRecoveryWords {"
    echo "    static let text = #\"\"\""
    cat ../spec/recovery-words-ru.txt
    echo "\"\"\"#"
    echo "}"
} > "$OUT"
echo "Wrote $OUT"

OUT=Sources/RedakciyaKit/Gazette/BundledGazetteTemplates.swift
{
    echo "// Generated by scripts/sync-spec.sh from spec/gazette/ru/templates.txt. Do not edit."
    echo "enum BundledGazetteTemplates {"
    echo "    static let text = #\"\"\""
    cat ../spec/gazette/ru/templates.txt
    echo "\"\"\"#"
    echo "}"
} > "$OUT"
echo "Wrote $OUT"
